"""
Citation Check & Grounding Verification for Veridocs.
Performs honest n-gram word overlap and citation verification between generated answers
and retrieved document chunks. No fabricated scores or fake triad metrics.
"""

import re
import logging
from typing import List, Dict, Optional, Any

logger = logging.getLogger(__name__)


def extract_citations_from_answer(
    answer: str,
    source_chunks: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """Extract citation references [Page X] or [Page X: filename] and match to source chunks."""
    citations = []
    # Match patterns: [Page 1], [Page 2: doc.pdf], [1], etc.
    matches = re.finditer(r'\[(?:Page\s*(\d+)(?::\s*([^\]]+))?|(\d+))\]', answer, re.IGNORECASE)

    seen = set()
    citation_id = 1

    for m in matches:
        raw_page = m.group(1) or m.group(3)
        doc_hint = m.group(2)
        if not raw_page:
            continue
        try:
            page = int(raw_page)
        except ValueError:
            continue

        # Find matching chunk
        matched_chunk = None
        for chunk in source_chunks:
            if chunk.get("page") == page:
                if doc_hint and doc_hint.lower() in chunk.get("source_file", "").lower():
                    matched_chunk = chunk
                    break
                elif not matched_chunk:
                    matched_chunk = chunk

        source_file = matched_chunk.get("source_file", "Document") if matched_chunk else (doc_hint or "Document")
        key = (source_file, page)
        if key in seen:
            continue
        seen.add(key)

        snippet = matched_chunk.get("text", "")[:250] if matched_chunk else ""

        citations.append({
            "citation_id": citation_id,
            "page": page,
            "source_file": source_file,
            "highlighted_text": snippet,
        })
        citation_id += 1

    # Fallback if no inline citation markers were generated by LLM: use top chunk
    if not citations and source_chunks:
        top = source_chunks[0]
        citations.append({
            "citation_id": 1,
            "page": top.get("page", 1),
            "source_file": top.get("source_file", "Document"),
            "highlighted_text": top.get("text", "")[:250],
        })

    return citations


def check_citations(
    answer: str,
    source_chunks: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """Verify how well statements in the answer are supported by retrieved source text using n-gram overlap."""
    if not answer or not source_chunks:
        return {
            "citation_score": 0.0,
            "total_claims": 0,
            "supported_claims": 0,
            "claims": []
        }

    raw_sentences = re.split(r'(?<=[.!?])\s+', answer)
    claims = []
    for s in raw_sentences:
        clean = re.sub(r'\[[^\]]*\]', '', s).strip()
        clean = re.sub(r'[*#`]', '', clean).strip()
        if len(clean) >= 15 and not clean.endswith('?'):
            claims.append(clean)

    if not claims:
        return {
            "citation_score": 1.0,
            "total_claims": 0,
            "supported_claims": 0,
            "claims": []
        }

    stopwords = {
        "the", "a", "an", "and", "or", "is", "are", "was", "were", "be", "been",
        "with", "for", "of", "in", "on", "to", "at", "by", "from", "it", "its",
        "as", "that", "this", "these", "those"
    }

    claim_results = []
    supported_count = 0

    for claim in claims:
        claim_lower = claim.lower()
        tokens = set(re.findall(r'\b[a-z0-9]{3,}\b', claim_lower)) - stopwords
        if not tokens:
            continue

        best_overlap = 0.0
        best_chunk = None

        for chunk in source_chunks:
            chunk_tokens = set(re.findall(r'\b[a-z0-9]{3,}\b', chunk.get("text", "").lower()))
            if not chunk_tokens:
                continue
            overlap = len(tokens & chunk_tokens) / len(tokens)
            if overlap > best_overlap:
                best_overlap = overlap
                best_chunk = chunk

        is_supported = best_overlap >= 0.35
        if is_supported:
            supported_count += 1

        claim_results.append({
            "claim": claim,
            "overlap_score": round(best_overlap, 2),
            "is_supported": is_supported,
            "matched_page": best_chunk.get("page") if best_chunk else None,
            "source_file": best_chunk.get("source_file") if best_chunk else None,
        })

    total = len(claim_results)
    score = round(supported_count / max(total, 1), 2)

    return {
        "citation_score": score,
        "total_claims": total,
        "supported_claims": supported_count,
        "claims": claim_results
    }
